//! Validates the fuzz seed corpus.
//!
//! Seeds are only useful if they are actually valid archives; a seed the reader
//! rejects contributes nothing but makes the corpus look bigger. Run after
//! changing `fuzz/gen_seeds.py`:
//!
//! ```text
//! python3 fuzz/gen_seeds.py && cargo run --example seedcheck
//! ```
//!
//! They are generated by Python, independently of `tests/writer.rs`, so
//! agreement here is a third implementation cross-checking the reader.

fn main() {
    let dir = std::path::Path::new("fuzz/seeds");
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .expect("fuzz/seeds should exist -- run: python3 fuzz/gen_seeds.py")
        .map(|e| e.expect("dir entry").path())
        .collect();
    files.sort();

    let mut bad = 0;
    for p in &files {
        let name = p.file_name().unwrap_or_default().to_string_lossy();
        let data = std::fs::read(p).expect("read seed");
        match zipview::ZipReader::new(&data) {
            Ok(r) => {
                let readable = r
                    .entries()
                    .iter()
                    .filter(|e| r.read_entry(e).is_ok())
                    .count();
                println!("{name:<18} OK  entries={} readable={}", r.len(), readable);
            }
            Err(e) => {
                // Not fatal: a deliberately malformed seed is legitimate. But
                // it should be a choice, so it is reported loudly.
                println!("{name:<18} REJECTED  {e}");
                bad += 1;
            }
        }
    }
    println!("\n{} seed(s), {} rejected", files.len(), bad);
}
